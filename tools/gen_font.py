"""Generates main/display_font.h: two anti-aliased (4-bit alpha) proportional
fonts for the on-device display, ASCII 32..126, from DejaVu Sans (Bitstream
Vera license, free to embed). Run: python3 tools/gen_font.py
"""
import os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = [  # (C name, ttf, pixel size)
    ('font_big', '/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf', 17),
    ('font_small', '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf', 11),
]

out = ['// Generated by tools/gen_font.py from DejaVu Sans (Bitstream Vera license).',
       '// 4-bit alpha, two pixels per byte (high nibble first), rows packed.',
       '#pragma once', '#include <stdint.h>', '',
       'typedef struct { uint16_t offset; uint8_t w, adv; int8_t x0; } glyph_t;',
       'typedef struct { const glyph_t *g; const uint8_t *bits; uint8_t height, ascent; } font_t;', '']
for name, path, size in FONTS:
    f = ImageFont.truetype(path, size)
    ascent, descent = f.getmetrics()
    h = ascent + descent
    glyphs, bits = [], bytearray()
    for c in range(32, 127):
        ch = chr(c)
        adv = round(f.getlength(ch))
        l, t, r, b = f.getbbox(ch)
        w = max(0, r - min(l, 0)) if ch != ' ' else 0
        x0 = min(l, 0)
        img = Image.new('L', (max(w, 1), h), 0)
        ImageDraw.Draw(img).text((-x0, 0), ch, font=f, fill=255)
        glyphs.append((len(bits), w, adv, x0))
        px = list(img.getdata()) if w else []
        nib = [p >> 4 for p in px]
        if len(nib) % 2: nib.append(0)
        for i in range(0, len(nib), 2):
            bits.append((nib[i] << 4) | nib[i + 1])
    out.append(f'static const glyph_t {name}_glyphs[95] = {{')
    out += [f'    {{ {o}, {w}, {a}, {x} }},' for o, w, a, x in glyphs]
    out.append('};')
    out.append(f'static const uint8_t {name}_bits[{len(bits)}] = {{')
    for i in range(0, len(bits), 24):
        out.append('    ' + ', '.join(f'0x{x:02x}' for x in bits[i:i + 24]) + ',')
    out.append('};')
    out.append(f'static const font_t {name} = {{ {name}_glyphs, {name}_bits, {h}, {ascent} }};')
    out.append('')
open(os.path.join(ROOT, 'main', 'display_font.h'), 'w').write('\n'.join(out))
print('ok', [(n, s) for n, _, s in FONTS])
